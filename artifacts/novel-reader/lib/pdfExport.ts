// Long-novel PDF export.
//
// The print engine (expo-print) takes the whole document as one HTML string, so
// the full novel must exist as text before printing starts. These steps keep that
// as small as possible and keep the peak low:
//
// - Each chapter is read alone and turned into one HTML fragment. The chapter
//   text is dropped as soon as its fragment exists.
// - The fragments are collected in an array and joined once, not built up by
//   repeated string concatenation.
// - The markup is lean: one stylesheet, classes instead of inline styles, no
//   web fonts. A system serif font is used.
// - The task yields to the UI between chapters, so the progress card keeps moving.
// - The size of the document is checked while it is built. If it would exceed
//   the limit, the export stops before printing and says so.
// - Cancel is checked between chapters. Nothing is printed after a cancel.
//
// The print and file functions are injected, so this runs in tests without a device.

import { requiredFreeBytes } from "./exportRunner";

// Largest HTML document passed to the print engine, in characters. Chosen
// conservatively for low-end phones; to be tuned after testing on a device.
export const PDF_MAX_HTML_CHARS = 20_000_000;

const INVALID = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\uFFFE\uFFFF]/g;

export function escapeHtml(value: string): string {
  return value
    .replace(INVALID, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export const PDF_STYLE = `    @page { size: letter; margin: 1in; }
    body { font-family: 'Times New Roman', Times, serif; font-size: 12pt; line-height: 1.5; color: #000; }
    .title-page { text-align: center; padding-top: 3in; page-break-after: always; }
    .title-page h1 { font-size: 24pt; margin-bottom: 12pt; }
    .title-page p { font-size: 14pt; color: #555; }
    .title-page .generated { margin-top: 2in; font-size: 10pt; color: #999; }
    .chapter-title { font-size: 16pt; font-weight: bold; margin-top: 24pt; margin-bottom: 12pt; page-break-before: always; text-align: center; }
    .chapter-content { text-align: justify; white-space: pre-wrap; }
    .footer { text-align: center; font-size: 9pt; color: #999; margin-top: 24pt; }`;

export function pdfHead(title: string, author: string): string {
  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8">
  <style>
${PDF_STYLE}
  </style>
</head>
<body>
  <div class="title-page">
    <h1>${escapeHtml(title)}</h1>
    <p>by ${escapeHtml(author)}</p>
    <p class="generated">Generated by Novel DR</p>
  </div>
`;
}

export function chapterFragment(title: string, content: string): string {
  return `  <div class="chapter-title">${escapeHtml(title)}</div>
  <div class="chapter-content">${escapeHtml(content)}</div>
`;
}

export function pdfTail(title: string): string {
  return `  <div class="footer">
    <p>End of ${escapeHtml(title)}</p>
  </div>
</body>
</html>`;
}

export type PdfSourceChapter = { index: number; title: string };

export type PdfBuildDeps = {
  readChapter: (
    index: number,
  ) => Promise<{ title: string; content: string } | null>;
  yieldToUi: () => Promise<void>;
  isCancelled: () => boolean;
  maxChars?: number;
  onChapter?: (done: number, total: number) => void;
};

export type PdfBuildResult =
  | { status: "ok"; html: string; missing: number }
  | { status: "cancelled" }
  | { status: "refused"; message: string; chaptersRead: number };

export async function buildPdfHtml(
  input: { title: string; author: string; chapters: PdfSourceChapter[] },
  deps: PdfBuildDeps,
): Promise<PdfBuildResult> {
  const maxChars = deps.maxChars ?? PDF_MAX_HTML_CHARS;
  const fragments: string[] = [pdfHead(input.title, input.author)];
  let size = fragments[0].length;
  let missing = 0;

  for (let i = 0; i < input.chapters.length; i++) {
    if (deps.isCancelled()) return { status: "cancelled" };

    const source = input.chapters[i];
    const data = await deps.readChapter(source.index);
    let title: string;
    let content: string;
    if (data && data.content.trim().length > 0) {
      title = data.title || source.title || `Chapter ${source.index + 1}`;
      content = data.content;
    } else {
      missing++;
      title = source.title || `Chapter ${source.index + 1}`;
      content =
        "[This chapter has no saved content. Re-download it from the Updates tab.]";
    }

    const fragment = chapterFragment(title, content);
    size += fragment.length;
    if (size > maxChars) {
      return {
        status: "refused",
        message: `This novel is too large to print as one PDF on this device (stopped at chapter ${i + 1} of ${input.chapters.length}). Use EPUB, DOCX, TXT, or RTF instead.`,
        chaptersRead: i + 1,
      };
    }
    fragments.push(fragment);
    deps.onChapter?.(i + 1, input.chapters.length);
    await deps.yieldToUi();
  }

  fragments.push(pdfTail(input.title));
  return { status: "ok", html: fragments.join(""), missing };
}

export type PdfExportDeps = PdfBuildDeps & {
  freeBytes: () => Promise<number>;
  // Prints the HTML with expo-print and returns the temporary PDF path.
  printToFile: (html: string) => Promise<string>;
  // Moves the printed PDF to its final path.
  moveFile: (from: string, to: string) => Promise<void>;
  onEvent?: (level: "info" | "ok" | "warn" | "error", text: string) => void;
};

export type PdfExportResult = {
  phase: "done" | "cancelled" | "refused" | "failed";
  pdfPath?: string;
  missing: number;
  note: string;
};

export async function exportLongPdf(
  input: {
    title: string;
    author: string;
    chapters: PdfSourceChapter[];
    finalPath: string;
    estimatedOutputBytes?: number;
  },
  deps: PdfExportDeps,
): Promise<PdfExportResult> {
  const free = await deps.freeBytes();
  const required = requiredFreeBytes({
    estimatedOutputBytes: input.estimatedOutputBytes,
  });
  if (free < required) {
    const note = `Not enough free space: ${Math.round(free / 1048576)} MB free, ${Math.round(required / 1048576)} MB needed.`;
    deps.onEvent?.("error", note);
    return { phase: "refused", missing: 0, note };
  }

  deps.onEvent?.(
    "info",
    `Building PDF from ${input.chapters.length} chapters.`,
  );
  const built = await buildPdfHtml(input, deps);

  if (built.status === "cancelled") {
    deps.onEvent?.("warn", "Cancelled. Nothing was printed.");
    return {
      phase: "cancelled",
      missing: 0,
      note: "Cancelled. No PDF was created.",
    };
  }
  if (built.status === "refused") {
    deps.onEvent?.("error", built.message);
    return { phase: "refused", missing: 0, note: built.message };
  }

  if (built.missing > 0) {
    deps.onEvent?.(
      "warn",
      `${built.missing} chapter${built.missing === 1 ? "" : "s"} had no saved content, placeholder used.`,
    );
  }
  deps.onEvent?.("info", "Printing PDF.");
  try {
    const tempPath = await deps.printToFile(built.html);
    await deps.moveFile(tempPath, input.finalPath);
    deps.onEvent?.("ok", "PDF ready to share.");
    return {
      phase: "done",
      pdfPath: input.finalPath,
      missing: built.missing,
      note: "PDF created.",
    };
  } catch (error: any) {
    const message =
      error?.message || "The print engine could not create the PDF.";
    deps.onEvent?.("error", `Printing failed: ${message}`);
    return {
      phase: "failed",
      missing: built.missing,
      note: `Printing failed: ${message}. Try EPUB, DOCX, TXT, or RTF.`,
    };
  }
}
